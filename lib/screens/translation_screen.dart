import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../network/network.dart';

class UniversalTranslationScreen extends ConsumerStatefulWidget {
  final String targetLanguage;
  final String voice;
  const UniversalTranslationScreen({
    Key? key,
    required this.targetLanguage,
    required this.voice,
  }) : super(key: key);

  @override
  ConsumerState<UniversalTranslationScreen> createState() =>
      _UniversalTranslationScreenState();
}

class _UniversalTranslationScreenState
    extends ConsumerState<UniversalTranslationScreen> {
  late final TextEditingController _translationController;

  @override
  void initState() {
    super.initState();
    final state = ref.read(localizationProvider);
    _translationController = TextEditingController(
      text: state.translation ?? '',
    );
  }

  @override
  Widget build(BuildContext context) {
    final state = ref.watch(localizationProvider);

    return Scaffold(
      appBar: AppBar(
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios, size: 20),
          onPressed: () => Navigator.pop(context),
        ),
        backgroundColor: Colors.transparent,
        elevation: 0,
      ),
      body: SafeArea(
        child: Padding(
          padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 10.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Center(
                child: Text(
                  '${widget.targetLanguage} Translation',
                  style: const TextStyle(
                    fontSize: 22,
                    fontWeight: FontWeight.bold,
                    color: Color(0xFF1E1B4B),
                  ),
                ),
              ),
              const SizedBox(height: 8),
              const Center(
                child: Text(
                  'Generated by N-ATLAS. Review and edit\nbefore generating speech.',
                  textAlign: TextAlign.center,
                  style: TextStyle(fontSize: 14, color: Color(0xFF64748B)),
                ),
              ),
              const SizedBox(height: 24),

              // Editable translation card
              Container(
                padding: const EdgeInsets.all(16),
                decoration: BoxDecoration(
                  color: Colors.white,
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(color: const Color(0xFFE2E8F0)),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      '${widget.targetLanguage} Translation',
                      style: const TextStyle(
                        fontSize: 13,
                        fontWeight: FontWeight.bold,
                        color: Color(0xFF64748B),
                      ),
                    ),
                    const SizedBox(height: 12),
                    state.isLoading
                        ? const Center(
                            child: CircularProgressIndicator(
                              color: Color(0xFF2C248A),
                            ),
                          )
                        : TextField(
                            controller: _translationController,
                            maxLines: 6,
                            style: const TextStyle(
                              fontSize: 15,
                              color: Color(0xFF1E1B4B),
                              height: 1.5,
                            ),
                            decoration: const InputDecoration.collapsed(
                              hintText: 'Translation text...',
                            ),
                          ),
                    const SizedBox(height: 12),
                    Align(
                      alignment: Alignment.centerRight,
                      child: Text(
                        '${_translationController.text.length}/500',
                        style: const TextStyle(
                          fontSize: 12,
                          color: Color(0xFF94A3B8),
                        ),
                      ),
                    ),
                  ],
                ),
              ),

              const SizedBox(height: 16),

              // Regenerate Button -> Re-triggers backend translation API
              OutlinedButton.icon(
                onPressed: () => ref
                    .read(localizationProvider.notifier)
                    .translateText(widget.targetLanguage),
                icon: const Icon(
                  Icons.refresh,
                  size: 18,
                  color: Color(0xFF2C248A),
                ),
                label: const Text(
                  'Regenerate Translation',
                  style: TextStyle(
                    color: Color(0xFF2C248A),
                    fontWeight: FontWeight.w600,
                  ),
                ),
                style: OutlinedButton.styleFrom(
                  minimumSize: const Size(double.infinity, 50),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(14),
                  ),
                  side: const BorderSide(color: Color(0xFFCBD5E1)),
                ),
              ),

              const Spacer(),

              // Continue saves the edited text and opens voice selection.
              ElevatedButton(
                onPressed: () {
                  ref
                      .read(localizationProvider.notifier)
                      .updateTranslation(_translationController.text);
                  Navigator.pushNamed(
                    context,
                    '/generateVoice',
                    arguments: {
                      'language': widget.targetLanguage,
                      'voice': widget.voice,
                    },
                  );
                },
                style: ElevatedButton.styleFrom(
                  backgroundColor: const Color(0xFF2C248A),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(16),
                  ),
                  minimumSize: const Size(double.infinity, 56),
                ),
                child: Row(
                  mainAxisAlignment: MainAxisAlignment.center,
                  children: const [
                    Text(
                      'Continue',
                      style: TextStyle(
                        fontSize: 16,
                        fontWeight: FontWeight.w600,
                        color: Colors.white,
                      ),
                    ),
                    SizedBox(width: 8),
                    Icon(Icons.arrow_forward, size: 20, color: Colors.white),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
